export const emmentalerDigits = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'];

export function isEmmentalerFont(name: string): boolean {
  return /^Emmentaler-\d+$/.test(name);
}

export function emmentalerGlyph(name: string): string {
  const digit = emmentalerDigits.indexOf(name);
  const code = digit < 0 ? symbols.get(name) : 0xe080 + digit;
  return code === undefined ? '' : String.fromCodePoint(code);
}
